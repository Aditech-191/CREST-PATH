private val CrestPathDarkColorScheme = darkColorScheme(
    primary = EmeraldPrimaryDark,
    onPrimary = OnEmeraldPrimaryDark,
    primaryContainer = EmeraldContainerDark,
    onPrimaryContainer = OnEmeraldContainerDark,
    secondary = CraneGoldSecondaryDark,
    onSecondary = OnCraneGoldSecondaryDark,
    secondaryContainer = CraneGoldContainerDark,
    onSecondaryContainer = OnCraneGoldContainerDark,
    tertiary = TerracottaTertiaryDark,
    onTertiary = OnTerracottaTertiaryDark,
    tertiaryContainer = TerracottaContainerDark,
    onTertiaryContainer = OnTerracottaContainerDark,
    background = SavannahBackgroundDark,
    onBackground = SoftIvoryOnBackgroundDark,
